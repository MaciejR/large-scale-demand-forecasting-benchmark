"""Compute Source B FM contrasts against a prespecified baseline.

The main Source B table uses the best observed baseline within each
dataset-horizon cell.  This script fixes the comparator in advance, defaulting
to tuned recursive LightGBM (`lightgbm_tuned_cov`), and recomputes paired
series-bootstrap log-ratios from the generated per-series metrics.
"""

from __future__ import annotations

import argparse
import zlib
from pathlib import Path

import numpy as np
import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_METRICS = ROOT / "analysis" / "figures" / "source_b_paired_panel_per_series_metrics.csv"
DEFAULT_OUTPUT_DIR = ROOT / "analysis" / "figures"
FM_MODELS = ["chronos2", "chronos_bolt_tiny", "moirai2", "timesfm25", "tirex"]


def _seed(seed: int, label: str) -> int:
    return (int(seed) + zlib.crc32(label.encode("utf-8"))) % (2**32)


def aggregate_wape(frame: pd.DataFrame, idx: np.ndarray | None = None) -> float:
    data = frame if idx is None else frame.iloc[idx]
    return float(data["abs_error"].sum() / data["abs_y"].sum())


def compute_contrasts(
    metrics: pd.DataFrame,
    baseline_model: str,
    n_bootstrap: int,
    seed: int,
) -> pd.DataFrame:
    rows = []
    key_cols = ["dataset", "horizon"]
    for (dataset, horizon), group in metrics.groupby(key_cols, sort=True):
        baseline = group[group["model_name"].eq(baseline_model)][["series_id", "abs_error", "abs_y"]]
        if baseline.empty:
            continue
        for model_name in FM_MODELS:
            model = group[group["model_name"].eq(model_name)][["series_id", "abs_error", "abs_y"]]
            if model.empty:
                continue
            paired = model.merge(
                baseline,
                on="series_id",
                suffixes=("_model", "_baseline"),
                how="inner",
            ).sort_values("series_id")
            if paired.empty:
                continue
            model_frame = paired[["abs_error_model", "abs_y_model"]].rename(
                columns={"abs_error_model": "abs_error", "abs_y_model": "abs_y"}
            )
            baseline_frame = paired[["abs_error_baseline", "abs_y_baseline"]].rename(
                columns={"abs_error_baseline": "abs_error", "abs_y_baseline": "abs_y"}
            )
            model_wape = aggregate_wape(model_frame)
            baseline_wape = aggregate_wape(baseline_frame)
            rng = np.random.default_rng(_seed(seed, f"{dataset}-{horizon}-{model_name}-{baseline_model}"))
            boot = []
            n = len(paired)
            for _ in range(n_bootstrap):
                idx = rng.integers(0, n, size=n)
                mw = aggregate_wape(model_frame, idx)
                bw = aggregate_wape(baseline_frame, idx)
                if mw > 0 and bw > 0 and np.isfinite(mw) and np.isfinite(bw):
                    boot.append(float(np.log(mw / bw)))
            boot_arr = np.asarray(boot)
            rows.append(
                {
                    "dataset": dataset,
                    "horizon": int(horizon),
                    "model_name": model_name,
                    "baseline_model": baseline_model,
                    "n_series": int(n),
                    "model_WAPE_aggregate": model_wape,
                    "baseline_WAPE_aggregate": baseline_wape,
                    "log_ratio": float(np.log(model_wape / baseline_wape)),
                    "bootstrap_se": float(np.std(boot_arr, ddof=1)) if len(boot_arr) > 1 else np.nan,
                    "ci95_low": float(np.quantile(boot_arr, 0.025)) if len(boot_arr) else np.nan,
                    "ci95_high": float(np.quantile(boot_arr, 0.975)) if len(boot_arr) else np.nan,
                    "n_boot": int(len(boot_arr)),
                }
            )
    return pd.DataFrame(rows).sort_values(["dataset", "horizon", "model_name"])


def write_chronos_table(contrasts: pd.DataFrame, output_path: Path) -> None:
    rows = contrasts[contrasts["model_name"].eq("chronos2")].sort_values(["dataset", "horizon"])
    lines = [
        "% Generated by analysis/source_b_prespecified_baseline_sensitivity.py",
        "\\begin{tabular}{llrrr}",
        "\\toprule",
        "Dataset & $h$ & FM WAPE & Baseline WAPE & $\\ell$ [95\\% CI] \\\\",
        "\\midrule",
    ]
    for row in rows.itertuples(index=False):
        lines.append(
            f"{row.dataset} & {int(row.horizon)} & {row.model_WAPE_aggregate:.3f} & "
            f"{row.baseline_WAPE_aggregate:.3f} & "
            f"{row.log_ratio:.3f} [{row.ci95_low:.3f}, {row.ci95_high:.3f}] \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabular}", ""])
    output_path.write_text("\n".join(lines), encoding="utf-8")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--metrics", type=Path, default=DEFAULT_METRICS)
    parser.add_argument("--baseline-model", default="lightgbm_tuned_cov")
    parser.add_argument("--n-bootstrap", type=int, default=1000)
    parser.add_argument("--seed", type=int, default=20260714)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    metrics = pd.read_csv(args.metrics)
    metrics["series_id"] = metrics["series_id"].astype(str)
    contrasts = compute_contrasts(metrics, args.baseline_model, args.n_bootstrap, args.seed)
    out_csv = args.output_dir / f"source_b_prespecified_{args.baseline_model}_contrasts.csv"
    out_tex = args.output_dir / f"source_b_prespecified_{args.baseline_model}_chronos2.tex"
    contrasts.to_csv(out_csv, index=False)
    write_chronos_table(contrasts, out_tex)
    print(f"Wrote {len(contrasts)} prespecified-baseline contrasts to {out_csv}")


if __name__ == "__main__":
    main()
