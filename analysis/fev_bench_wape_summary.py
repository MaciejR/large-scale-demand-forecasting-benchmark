#!/usr/bin/env python3
"""Summarise fev-bench prediction-level WAPE repair outputs."""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd


FIGURES_DIR = Path("analysis/figures")

MODEL_INPUTS = [
    ("Chronos-Bolt-Tiny", "chronos_bolt_tiny", "fev_chronos_bolt_paired_wape"),
    ("Chronos-2", "chronos2", "fev_chronos2_paired_wape"),
    ("TiRex", "tirex", "fev_tirex_paired_wape"),
    ("TimesFM 2.5", "timesfm25", "fev_timesfm25_paired_wape"),
]


def _fmt_int(value: int) -> str:
    return f"{value:,}"


def build_summary(figures_dir: Path = FIGURES_DIR) -> pd.DataFrame:
    rows = []
    for label, model_name, prefix in MODEL_INPUTS:
        path = figures_dir / f"{prefix}_contrasts.csv"
        if not path.exists():
            continue
        contrasts = pd.read_csv(path)
        rows.append(
            {
                "model_label": label,
                "model_name": model_name,
                "tasks": contrasts["task_name"].nunique(),
                "paired_units": int(contrasts["n_pairs"].sum()),
                "valid_units": int(contrasts["n_valid_pairs"].sum()),
                "median_log_ratio": contrasts["log_ratio"].median(),
                "mean_log_ratio": contrasts["log_ratio"].mean(),
                "median_ratio": float(np.exp(contrasts["log_ratio"].median())),
                "point_fm_better_tasks": int((contrasts["log_ratio"] < 0).sum()),
                "ci_fm_better_tasks": int((contrasts["ci_high"] < 0).sum()),
                "ci_baseline_better_tasks": int((contrasts["ci_low"] > 0).sum()),
            }
        )
    return pd.DataFrame(rows)


def write_latex(summary: pd.DataFrame, output_path: Path) -> None:
    lines = [
        "% Generated by analysis/fev_bench_wape_summary.py",
        r"\begin{tabular}{lrrrrrr}",
        r"\toprule",
        r"Model & Tasks & Paired units & Median $\ell$ & Mean $\ell$ & FM better & CI excludes 0 \\",
        r"\midrule",
    ]
    for row in summary.itertuples(index=False):
        lines.append(
            f"{row.model_label} & {row.tasks} & {_fmt_int(row.paired_units)} & "
            f"${row.median_log_ratio:.3f}$ & ${row.mean_log_ratio:.3f}$ & "
            f"{row.point_fm_better_tasks}/{row.tasks} & "
            f"{row.ci_fm_better_tasks}/{row.tasks} \\\\"
        )
    lines.extend([r"\bottomrule", r"\end{tabular}", ""])
    output_path.write_text("\n".join(lines))


def main() -> None:
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    summary = build_summary(FIGURES_DIR)
    summary.to_csv(FIGURES_DIR / "fev_prediction_level_wape_summary.csv", index=False)
    write_latex(summary, FIGURES_DIR / "fev_prediction_level_wape_summary.tex")
    print(summary.to_string(index=False))


if __name__ == "__main__":
    main()
